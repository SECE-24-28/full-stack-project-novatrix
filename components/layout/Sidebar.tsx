export function Sidebar() {
  const pathname = usePathname();
  const { user } = useAuth();

  const visibleItems = NAV_ITEMS.filter(({ permission }) => {
    if (!user) return false;
    const perms    = ROLE_PERMISSIONS[user.role] ?? [];
    const resource = permission.split(":")[1] as string;
    return (
      perms.includes(permission) ||
      perms.includes(`manage:${resource}` as Permission)
    );
  });

  return (
    <aside className="flex h-full w-64 flex-col border-r border-gray-200 bg-white">
      <div className="flex h-16 items-center border-b border-gray-200 px-6">
        <span className="text-lg font-bold text-blue-600">IWMS</span>
      </div>
      <nav className="flex-1 overflow-y-auto p-4">
        {/* Main nav */}
        <ul className="space-y-1">
          {visibleItems
            .filter((i) => !i.href.startsWith("/reports") && i.href !== "/audit-log")
            .map((item) => (
              <li key={item.href}>
                <Link
                  href={item.href}
                  className={cn(
                    "flex items-center gap-3 rounded-md px-3 py-2 text-sm font-medium transition-colors",
                    pathname === item.href || (item.href !== "/dashboard" && pathname.startsWith(item.href))
                      ? "bg-blue-50 text-blue-700"
                      : "text-gray-600 hover:bg-gray-100 hover:text-gray-900"
                  )}
                >
                  {item.icon}
                  {item.label}
                </Link>
              </li>
            ))}
        </ul>

        {/* Audit Log group */}
        {visibleItems.some((i) => i.href === "/audit-log") && (
          <div className="mt-5">
            <p className="mb-1.5 px-3 text-[10px] font-semibold uppercase tracking-widest text-gray-400">Audit</p>
            <ul className="space-y-1">
              {visibleItems
                .filter((i) => i.href === "/audit-log")
                .map((item) => (
                  <li key={item.href}>
                    <Link
                      href={item.href}
                      className={cn(
                        "flex items-center gap-3 rounded-md px-3 py-2 text-sm font-medium transition-colors",
                        pathname.startsWith(item.href)
                          ? "bg-blue-50 text-blue-700"
                          : "text-gray-600 hover:bg-gray-100 hover:text-gray-900"
                      )}
                    >
                      {item.icon}
                      {item.label}
                    </Link>
                  </li>
                ))}
            </ul>
          </div>
        )}

        {/* Reports group */}
        {visibleItems.some((i) => i.href.startsWith("/reports")) && (
          <div className="mt-5">
            <p className="mb-1.5 px-3 text-[10px] font-semibold uppercase tracking-widest text-gray-400">Reports</p>
            <ul className="space-y-1">
              {visibleItems
                .filter((i) => i.href.startsWith("/reports"))
                .map((item) => (
                  <li key={item.href}>
                    <Link
                      href={item.href}
                      className={cn(
                        "flex items-center gap-3 rounded-md px-3 py-2 text-sm font-medium transition-colors",
                        pathname.startsWith(item.href)
                          ? "bg-blue-50 text-blue-700"
                          : "text-gray-600 hover:bg-gray-100 hover:text-gray-900"
                      )}
                    >
                      {item.icon}
                      {item.label}
                    </Link>
                  </li>
                ))}
            </ul>
          </div>
        )}
      </nav>
    </aside>
  );
}
